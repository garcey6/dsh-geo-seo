/**
 * F2: machine-readable asset generation.
 *
 * llms.txt, llms-full.txt, ai.txt and the JSON-LD payload are all rendered from
 * one FactGraph in a single pass, so the three text files cannot disagree with
 * each other. JSON-LD is verified against the visible text before anything is
 * written: if a field cannot be traced to the body, it is dropped, and if a
 * required field cannot be verified the write is refused with a diff report.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { FactGraph, GenerateFileResult, GenerateResult, MarkdownDoc } from './types.js';
import { bodyText, leadText } from './markdown.js';
import { RULE_PACK_VERSION } from './rules.js';
import { ENGINE_VERSION } from './types.js';
import { normalizeWhitespace, readTextSafe, sha1 } from './util.js';

export interface GenerateOptions {
  /** Directory to write into. Defaults to a scratch directory under the OS temp dir. */
  outDir?: string;
  /** Overwrite existing files. Without it, existing files are skipped, never clobbered. */
  force?: boolean;
  /** Render and verify but write nothing. */
  dryRun?: boolean;
  /** Maximum number of pages listed in llms.txt. */
  maxEntries?: number;
  /** Write only these asset file names; omitted or empty means all four. */
  names?: string[];
  now?: Date;
}

const MAX_ENTRIES = 20;
const MIN_ENTRIES = 10;
const MAX_FULL_CHARS = 240_000;

interface PageEntry {
  file: string;
  title: string;
  description: string;
}

/** Picks the core pages: README first, then docs, README of subfolders last. */
export function selectPages(graph: FactGraph, maxEntries = MAX_ENTRIES): PageEntry[] {
  const docs = [...graph.docs];
  const rank = (doc: MarkdownDoc): number => {
    if (doc.kind === 'readme' && !doc.file.includes('/')) return 0;
    if (doc.kind === 'readme') return 1;
    if (doc.kind === 'doc' && doc.file.startsWith('docs/')) return 2;
    if (doc.kind === 'doc') return 3;
    if (doc.kind === 'changelog') return 5;
    return 4;
  };
  return docs
    .sort((a, b) => rank(a) - rank(b) || a.file.localeCompare(b.file))
    .slice(0, maxEntries)
    .map((doc) => ({
      file: doc.file,
      title: doc.headings.find((heading) => heading.level === 1)?.text || titleFromFile(doc.file),
      description: summarize(doc),
    }));
}

function titleFromFile(file: string): string {
  const base = (file.split('/').pop() ?? file).replace(/\.mdx?$/i, '');
  return base.charAt(0).toUpperCase() + base.slice(1);
}

function summarize(doc: MarkdownDoc): string {
  // A lead blockquote ("> ...") is scaffolding, not a summary; strip its markers first.
  const lead = normalizeWhitespace(leadText(doc).replace(/^\s*>\s?/gm, ''));
  if (lead.length >= 30) return clipSentence(lead, 140);
  const paragraph = doc.paragraphs.find((item) => item.text.length >= 30);
  if (paragraph) return clipSentence(paragraph.text.replace(/^\s*>\s?/gm, ''), 140);
  const heading = doc.headings[0]?.text;
  return heading ? 'Section: ' + heading : 'Documentation page.';
}

function clipSentence(text: string, max: number): string {
  const flat = normalizeWhitespace(text);
  if (flat.length <= max) return flat;
  const cut = flat.slice(0, max);
  const stop = Math.max(cut.lastIndexOf('. '), cut.lastIndexOf('。'));
  return (stop > 60 ? cut.slice(0, stop + 1) : cut.trimEnd() + '…');
}

function header(comment: string, files: string[], now: Date): string {
  return [
    '<!-- ' + comment,
    '     generated by dsh-geo-seo ' + ENGINE_VERSION + ' (rule pack ' + RULE_PACK_VERSION + ')',
    '     at ' + now.toISOString() + ' from: ' + files.join(', '),
    '     do not edit by hand; run \`geo-seo generate\` again -->',
  ].join('\n');
}

export function buildLlmsTxt(graph: FactGraph, options: GenerateOptions = {}): { content: string; entries: PageEntry[] } {
  const now = options.now ?? new Date();
  const entries = selectPages(graph, options.maxEntries ?? MAX_ENTRIES);
  const name = graph.packageJson?.name ?? path.basename(graph.dir);
  const description =
    graph.packageJson?.description ??
    summarize(graph.docs.find((doc) => doc.kind === 'readme') ?? graph.docs[0] ?? emptyDoc());
  const sources = ['package.json', ...entries.map((entry) => entry.file)].filter((file, index, all) => all.indexOf(file) === index);

  const lines: string[] = [];
  lines.push(header('llms.txt - generated index for language models', sources, now));
  lines.push('');
  lines.push('# ' + name);
  lines.push('');
  lines.push('> ' + clipSentence(description, 240));
  lines.push('');
  const facts: string[] = [];
  if (graph.packageJson?.version) facts.push('- Version: ' + graph.packageJson.version);
  if (graph.packageJson?.license) facts.push('- License: ' + graph.packageJson.license);
  if (graph.packageJson?.repository) facts.push('- Repository: ' + graph.packageJson.repository);
  if (graph.packageJson?.homepage) facts.push('- Homepage: ' + graph.packageJson.homepage);
  if (graph.declaredUpdatedAt) facts.push('- Last updated: ' + graph.declaredUpdatedAt);
  else if (graph.git.lastCommitDate) facts.push('- Last commit: ' + graph.git.lastCommitDate);
  if (facts.length > 0) {
    lines.push(...facts);
    lines.push('');
  }
  lines.push('## Core pages');
  lines.push('');
  for (const entry of entries) {
    lines.push('- [' + entry.title + '](' + entry.file + '): ' + entry.description);
  }
  lines.push('');
  lines.push('## Optional');
  lines.push('');
  const extras: string[] = [];
  if (graph.files.includes('CHANGELOG.md')) extras.push('- [Changelog](CHANGELOG.md): Release history.');
  if (graph.files.includes('LICENSE')) extras.push('- [License](LICENSE): Terms of use.');
  if (graph.packageJson?.repository) extras.push('- [Repository](' + graph.packageJson.repository + '): Source code and issues.');
  if (extras.length === 0) extras.push('- No additional pages.');
  lines.push(...extras);
  lines.push('');

  return { content: lines.join('\n'), entries };
}

export function buildLlmsFullTxt(graph: FactGraph, options: GenerateOptions = {}): { content: string; pages: string[] } {
  const now = options.now ?? new Date();
  const entries = selectPages(graph, options.maxEntries ?? MAX_ENTRIES);
  const sources = ['package.json', ...entries.map((entry) => entry.file)];
  const chunks: string[] = [header('llms-full.txt - full text of the core pages', sources, now), ''];
  const pages: string[] = [];
  let budget = MAX_FULL_CHARS;

  for (const entry of entries) {
    const doc = graph.docs.find((item) => item.file === entry.file);
    if (!doc) continue;
    const text = normalizeWhitespace(bodyText(doc) + '\n' + codeSample(doc));
    const slice = text.length > budget ? text.slice(0, budget) : text;
    if (!slice) continue;
    budget -= slice.length;
    pages.push(entry.file);
    chunks.push('## ' + entry.title + ' (' + entry.file + ')');
    chunks.push('');
    chunks.push(slice);
    chunks.push('');
    if (budget <= 0) break;
  }
  return { content: chunks.join('\n'), pages };
}

function codeSample(doc: MarkdownDoc): string {
  const block = doc.codeBlocks[0];
  return block ? '\nExample:\n' + block.text : '';
}

function emptyDoc(): MarkdownDoc {
  return {
    file: 'README.md',
    kind: 'readme',
    raw: '',
    lineCount: 0,
    headings: [],
    paragraphs: [],
    lists: [],
    codeBlocks: [],
    tables: [],
    links: [],
    wordCount: 0,
    frontmatter: {},
    sections: [],
  };
}

export interface JsonLdBuild {
  value: Record<string, unknown>;
  /** Fields that were dropped because the body does not support them. */
  dropped: { field: string; reason: string }[];
  /** Required fields that could not be verified: when non-empty the write is refused. */
  blocking: { field: string; reason: string }[];
}

/**
 * Builds a SoftwareApplication payload from verifiable facts only. Nothing is
 * invented: no rating, no price, no aggregate, no areaServed.
 */
export function buildJsonLd(graph: FactGraph): JsonLdBuild {
  const dropped: { field: string; reason: string }[] = [];
  const blocking: { field: string; reason: string }[] = [];
  const doc = graph.docs.find((item) => item.kind === 'readme') ?? graph.docs[0];
  const visible = visibleTextOf(graph);

  const value: Record<string, unknown> = {
    '@context': 'https://schema.org',
    '@type': 'SoftwareApplication',
    applicationCategory: 'DeveloperApplication',
    _generatedBy: 'dsh-geo-seo ' + ENGINE_VERSION + ' / rule pack ' + RULE_PACK_VERSION,
  };

  const name = graph.packageJson?.name;
  if (name) {
    value['name'] = name;
    if (!visible.includes(name.toLowerCase())) {
      blocking.push({ field: 'name', reason: 'Package name "' + name + '" does not appear in the visible page text.' });
    }
  } else {
    blocking.push({ field: 'name', reason: 'package.json has no name.' });
  }

  const description = graph.packageJson?.description;
  if (description) {
    if (visible.includes(normalizeWhitespace(description).toLowerCase())) {
      value['description'] = description;
    } else {
      dropped.push({
        field: 'description',
        reason: 'package.json description is not present in the visible page text; copy it into the README to emit it.',
      });
    }
  } else {
    dropped.push({ field: 'description', reason: 'package.json has no description.' });
  }

  if (graph.packageJson?.version) {
    if (visible.includes(graph.packageJson.version.toLowerCase())) value['softwareVersion'] = graph.packageJson.version;
    else dropped.push({ field: 'softwareVersion', reason: 'Version not stated in the page text.' });
  }

  if (graph.packageJson?.license) value['license'] = graph.packageJson.license;

  const url = graph.packageJson?.homepage ?? graph.packageJson?.repository;
  if (url) value['url'] = url;

  const author = graph.packageJson?.author;
  if (author) {
    if (visible.includes(author.toLowerCase())) value['author'] = { '@type': 'Person', name: author };
    else dropped.push({ field: 'author', reason: 'Author name not stated on the page.' });
  }

  const keywords = graph.packageJson?.keywords ?? [];
  if (keywords.length > 0) value['keywords'] = keywords.join(', ');

  if (graph.git.lastCommitDate) value['dateModified'] = graph.git.lastCommitDate;

  return { value, dropped, blocking };
}

/** Lowercased visible text of every document, used for claim verification. */
function visibleTextOf(graph: FactGraph): string {
  const parts: string[] = [];
  for (const doc of graph.docs) parts.push(leadText(doc) + ' ' + bodyText(doc));
  return normalizeWhitespace(parts.join(' ')).toLowerCase();
}

/** Reduces a JSON-LD value to the text a reader would actually see. */
function flattenClaim(value: unknown): string {
  if (typeof value === 'string') return value;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return value.map(flattenClaim).join(' ');
  if (value && typeof value === 'object') {
    const record = value as Record<string, unknown>;
    if (typeof record['name'] === 'string') return record['name'];
    return Object.values(record).map(flattenClaim).join(' ');
  }
  return '';
}

export interface VerifyResult {
  ok: boolean;
  checkedFacts: number;
  mismatches: { kind: string; claim: string; evidence: string }[];
}

/** Cross-checks the rendered JSON-LD against the fact graph and the page text. */
export function verifyJsonLd(build: JsonLdBuild, graph: FactGraph): VerifyResult {
  const mismatches: { kind: string; claim: string; evidence: string }[] = [];
  const visible = visibleTextOf(graph);
  let checked = 0;

  /** Fields taken from configuration, not from page claims. */
  const NOT_A_CLAIM = new Set(['applicationCategory', 'license', 'url', 'keywords', 'dateModified']);

  for (const [field, value] of Object.entries(build.value)) {
    if (field.startsWith('@') || field.startsWith('_') || NOT_A_CLAIM.has(field)) continue;
    checked += 1;
    const text = flattenClaim(value);
    if (text.length < 2) continue;
    if (!visible.includes(normalizeWhitespace(text).toLowerCase())) {
      mismatches.push({
        kind: field,
        claim: text,
        evidence: 'Not found in the visible body text of the documentation',
      });
    }
  }

  for (const item of build.blocking) {
    mismatches.push({ kind: item.field, claim: 'required', evidence: item.reason });
  }

  // Ratings and prices must never appear unless the page shows them.
  const rating = build.value['aggregateRating'];
  if (rating) mismatches.push({ kind: 'aggregateRating', claim: JSON.stringify(rating), evidence: 'Generated output must not invent ratings.' });
  const offers = build.value['offers'];
  if (offers) mismatches.push({ kind: 'offers', claim: JSON.stringify(offers), evidence: 'Generated output must not invent prices.' });

  return { ok: mismatches.length === 0, checkedFacts: checked, mismatches };
}

/** Renders the JSON-LD file: valid JSON only, so provenance lives in a property. */
export function renderJsonLd(value: Record<string, unknown>): string {
  return JSON.stringify(value, null, 2) + '\n';
}

export function defaultOutDir(graph: FactGraph): string {
  return path.join(os.tmpdir(), 'geo-seo', sha1(graph.dir.toLowerCase()).slice(0, 10));
}

/** Generates all four assets. Never overwrites without \`force\`. */
export function generateAssets(graph: FactGraph, options: GenerateOptions = {}): GenerateResult {
  const now = options.now ?? new Date();
  const outDir = options.outDir ?? defaultOutDir(graph);
  const dryRun = Boolean(options.dryRun);

  const llms = buildLlmsTxt(graph, options);
  const full = buildLlmsFullTxt(graph, options);
  const jsonLd = buildJsonLd(graph);
  const verification = verifyJsonLd(jsonLd, graph);

  const warnings: string[] = [];
  if (llms.entries.length < MIN_ENTRIES) {
    warnings.push('Only ' + llms.entries.length + ' core pages; the PRD asks for 10-20.');
  }

  const files: GenerateFileResult[] = [];

  const only = options.names !== undefined && options.names.length > 0 ? new Set(options.names) : undefined;
  const wanted = (name: string): boolean => only === undefined || only.has(name);

  const writeFile = (name: string, content: string, extraWarnings: string[] = []): void => {
    if (!wanted(name)) return;
    const target = path.join(outDir, name);
    const result: GenerateFileResult = { path: target, bytes: Buffer.byteLength(content, 'utf8'), written: false, warnings: extraWarnings };
    if (dryRun) {
      result.reason = 'dry run';
      files.push(result);
      return;
    }
    try {
      fs.mkdirSync(outDir, { recursive: true });
      if (fs.existsSync(target) && !options.force) {
        const existing = readTextSafe(target, 8 * 1024 * 1024);
        if (existing !== content) {
          result.reason = 'exists with different content; pass --force to overwrite';
          files.push(result);
          return;
        }
        result.reason = 'unchanged';
        result.written = true;
        files.push(result);
        return;
      }
      fs.writeFileSync(target, content, 'utf8');
      result.written = true;
      files.push(result);
    } catch (error) {
      result.reason = 'write failed: ' + (error instanceof Error ? error.message : String(error));
      files.push(result);
    }
  };

  writeFile('llms.txt', llms.content, warnings);
  writeFile('llms-full.txt', full.content);
  writeFile('ai.txt', llms.content, ['mirror of llms.txt (alternate filename convention)']);

  if (!verification.ok && jsonLd.blocking.length > 0) {
    if (wanted('structured-data.jsonld')) files.push({
      path: path.join(outDir, 'structured-data.jsonld'),
      bytes: 0,
      written: false,
      reason: 'refused: ' + jsonLd.blocking.map((item) => item.field).join(', ') + ' cannot be verified against the visible text',
      warnings: [],
    });
  } else {
    const jsonWarnings = jsonLd.dropped.map((item) => item.field + ' dropped: ' + item.reason);
    writeFile('structured-data.jsonld', renderJsonLd(jsonLd.value), jsonWarnings);
  }

  return { dir: outDir, dryRun, files, verification };
}
